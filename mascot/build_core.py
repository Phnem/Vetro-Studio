"""Вырезает из mascot.html ядро маскота (риг + сцены, без режимов рендера роликов) в assets/js/mascot-core.js.

    python mascot/build_core.py

mascot.html остаётся единственным источником правды; mascot-core.js — генерируемый файл, руками не правится.
Ядро выставляет window.VetroMascot = { SCENES, ORDER, sceneSvg, setTheme } — см. docs/mascot.md.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "mascot.html"
DST = HERE.parent / "assets" / "js" / "mascot-core.js"

START = "<script>"
# Всё после этого комментария — режимы ролика (grid/solo/app), grain и renderAt: на сайте не нужны.
END = "/* ───────────────────────── режимы"

html = SRC.read_text(encoding="utf-8")
a = html.index(START) + len(START)
b = html.index(END)
core = html[a:b].strip("\n")

header = (
    "/* GENERATED by mascot/build_core.py from mascot/mascot.html — do not edit by hand.\n"
    "   Vetro mascot: rig + scenes as pure functions of time. Usage: docs/mascot.md */\n"
)
# IIFE: у ядра десятки глобальных const с короткими именами (E, C, Q, box, ticks…) — не пускаем их в код сайта.
footer = "\nwindow.VetroMascot = { SCENES, ORDER, sceneSvg, setTheme };\n})();\n"
DST.parent.mkdir(parents=True, exist_ok=True)
DST.write_text(header + "(() => {\n" + core + footer, encoding="utf-8", newline="\n")
print(f"{DST.relative_to(HERE.parent)}: {DST.stat().st_size / 1024:.1f} KB")
